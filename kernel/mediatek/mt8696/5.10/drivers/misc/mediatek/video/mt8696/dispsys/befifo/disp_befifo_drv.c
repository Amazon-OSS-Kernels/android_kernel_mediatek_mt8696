static void _befifo_mutex_init(void)
{
	mutex_init(&(_befifo_inst.lock));
}

static void _befifo_mutex_lock(void)
{
	mutex_lock(&(_befifo_inst.lock));
}

static void _befifo_mutex_unlock(void)
{
	mutex_unlock(&(_befifo_inst.lock));
}

void disp_befifo_drv_init(uintptr_t reg_base, enum HDMI_VIDEO_RESOLUTION res)
{
	memset((void *)&_befifo_inst, 0, sizeof(struct disp_befifo_context));
	_befifo_mutex_init();
	_befifo_inst.befifo_hw_base = reg_base;
	_befifo_inst.reg_conf_mode = BEFIFO_REG_CONF_CLIENT_RIU;
	_befifo_inst.io_reg_base = DISP_BEFIFO_REG_BASE;
	_befifo_inst.res = res;
	befifo_hal_init(reg_base);
	_befifo_inst.inited = true;
}

void disp_befifo_drv_uninit(void)
{
	_befifo_mutex_lock();
	befifo_hal_uninit();
	memset((void *)&_befifo_inst, 0, sizeof(struct disp_befifo_context));
	_befifo_mutex_unlock();
}

int disp_befifo_drv_set_gce_handle(void *pv_handle)
{
	if (!_befifo_inst.inited)
		return BEFIFO_RET_UNINIT;
	if (pv_handle == NULL)
		return BEFIFO_RET_INV_ARG;
	_befifo_inst.gce_handle = NULL;
	return BEFIFO_RET_OK;
}

int disp_befifo_drv_set_clk_enable(uint32_t enable)
{
	befifo_info(" %s [%d]!\n", __func__, enable);
	if (enable)
		disp_clock_enable(DISP_CLK_HDR_BE_FIFO, true);
	else
		disp_clock_enable(DISP_CLK_HDR_BE_FIFO, false);
	return BEFIFO_RET_OK;
}

int disp_befifo_drv_set_conf_mode(uint32_t mode)
{
	_befifo_inst.reg_conf_mode = mode;
	befifo_default(" %s conf mode[%d]!\n", __func__, mode);
	return BEFIFO_RET_OK;
}

int disp_befifo_map_timing(enum HDMI_VIDEO_RESOLUTION res,
	struct disp_befifo_timing *pst_timing)
{
	int i;
	struct disp_befifo_timing *tg_point = NULL;
	struct disp_befifo_timing *tg_table = &(befifo_timing_tbl[1][0]);

	if (pst_timing == NULL)
		return BEFIFO_RET_INV_ARG;

	if (res >= HDMI_VIDEO_RESOLUTION_NUM) {
		befifo_error("%s not support this res[%d]!\n",
			__func__, res);
		return -1;
	}

	for (i = 0; i < HDMI_VIDEO_RESOLUTION_NUM; i++) {
		if (tg_table[i].res == res) {
			tg_point = &tg_table[i];
			break;
		}
	}
	if (tg_point != NULL) {
		pst_timing->htotal = tg_point->htotal;
		pst_timing->vtotal_lsb = tg_point->vtotal_lsb;
		pst_timing->vtotal_msb = tg_point->vtotal_msb;
		pst_timing->width = tg_point->width;
		pst_timing->height = tg_point->height;
		pst_timing->hoffset = tg_point->hoffset;
		pst_timing->voffset = tg_point->voffset;
		pst_timing->hfront = tg_point->hfront;
		pst_timing->vfront = tg_point->vfront;
		pst_timing->hsync_w = tg_point->hsync_w;
		pst_timing->vsync_w = tg_point->vsync_w;
		pst_timing->res = tg_point->res;
	}
	return BEFIFO_RET_OK;
}

void disp_befifo_drv_set_resolution(uint32_t hw_id,
	enum HDMI_VIDEO_RESOLUTION res)
{
	struct disp_befifo_timing st_timing;

	_befifo_mutex_lock();
	disp_befifo_map_timing(res, &st_timing);
	befifo_hal_set_timing(&st_timing,
		_befifo_inst.reg_conf_mode);
	if (_befifo_inst.res != res) {
		befifo_hal_reset();
		_befifo_inst.res = res;
	}
	_befifo_mutex_unlock();
}

void disp_befifo_drv_get_resolution(uint32_t hw_id,
	enum HDMI_VIDEO_RESOLUTION *pe_res)
{
	if (pe_res != NULL)
		*pe_res = _befifo_inst.res;
}

void disp_befifo_drv_enable(bool fgEn, uint32_t mode)
{
	_befifo_mutex_lock();
	befifo_hal_set_shdw(true, true);
	befifo_hal_set_enable(fgEn, mode);
	_befifo_mutex_unlock();
}

void disp_befifo_drv_clr_irq(uint32_t irq)
{
	if (_befifo_inst.inited)
		befifo_hal_clr_isr(true, 0);
}

void disp_befifo_drv_flush_reg(uint32_t mode)
{
	if (_befifo_inst.inited)
		befifo_hal_isr(mode);
}

