void disp_befifo_drv_read_reg(uint32_t rel_offset, uint32_t size)
{
	uint32_t idx = 0;
	uintptr_t va_addr = 0;

	if (rel_offset < 0x1000) {
		for (idx = 0; idx < size; idx++) {
			va_addr =
			_befifo_inst.befifo_hw_base + rel_offset + idx * 4;
			befifo_default("0x%p = 0x%x\n",
				(void *)va_addr, ReadREG32(va_addr));
		}
	}
}

void disp_befifo_drv_write_reg(uint32_t rel_offset, uint32_t value)
{
	uintptr_t va_addr = _befifo_inst.befifo_hw_base;

	if (rel_offset < 0x1000) {
		va_addr += rel_offset;
		WriteREG32(va_addr, value);
		befifo_default("0x%p = 0x%x\n",
			(void *)va_addr, ReadREG32(va_addr));
	}
}

void disp_befifo_drv_adj_front(struct BEFIFO_ACTIVE_SHIFT_T *pt_shift)
{
	if (pt_shift != NULL) {
		befifo_hal_set_hdelay(pt_shift->hshitf, pt_shift->hpos);
		befifo_hal_set_hdelay(pt_shift->vshitf, pt_shift->vpos);
	}
}

void disp_befifo_drv_set_front(uint32_t front_h, uint32_t front_v)
{
	befifo_hal_set_front(front_h, front_v);
}

int disp_befifo_dbg_level_enable(uint32_t level, uint32_t enable)
{
	if (enable)
		befifo_dbg_level |= (1 << level);
	else
		befifo_dbg_level = 0;
	befifo_default("set befifo dbg level %d enable %d 0x%X\n",
		level, enable, befifo_dbg_level);
	return BEFIFO_RET_OK;
}

void disp_befifo_drv_set_pattern(uint32_t res_id, uint32_t enable,
	uint32_t y_data, uint32_t cb_data, uint32_t cr_data)
{
	struct disp_befifo_timing st_timing;
	struct disp_befifo_pattern stPattern;

	disp_befifo_map_timing((enum HDMI_VIDEO_RESOLUTION)res_id, &st_timing);
	stPattern.ypattern = y_data;
	stPattern.cbpattern = cb_data;
	stPattern.crpattern = cr_data;
	stPattern.ypattern_b = 0x100;
	stPattern.cbpattern_b = 0x800;
	stPattern.crpattern_b = 0x800;
	stPattern.mode = 1;
	befifo_hal_set_pattern((void *)&st_timing, enable, (void *)&stPattern);

}

int disp_befifo_drv_gce_trigger(void)
{
	int ret = BEFIFO_RET_OK;

	if (!_befifo_inst.inited || (_befifo_inst.gce_handle == NULL))
		return BEFIFO_RET_UNINIT;
	befifo_hal_isr(BEFIFO_REG_CONF_CLIENT_GCE);
	return ret;
}

