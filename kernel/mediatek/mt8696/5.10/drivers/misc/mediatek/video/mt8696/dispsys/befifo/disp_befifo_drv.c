{
	befifo_hal_enable_crc(enable, mode);
}

void disp_befifo_drv_set_output_swap(uint32_t swap_type)
{
	befifo_hal_set_out_swap(swap_type);
}

#ifdef DISP_QMS_SUPPORT
void disp_befifo_drv_set_vrr(bool fgEnable,
	uint32_t value, uint32_t mode)
{
	struct disp_befifo_timing st_timing;
	uint32_t u4Votal = 0;

	st_timing.vtotal_msb = 0;
	st_timing.vtotal_lsb = 0;

	if (fgEnable)
		befifo_hal_set_vtotal_ext(fgEnable, value, mode);
	else {
		// vrr disable and reset vtotal
		disp_befifo_map_timing(_befifo_inst.res, &st_timing);
		u4Votal = (((st_timing.vtotal_msb << 16) & 0xFFFF0000) |
			st_timing.vtotal_lsb);
		befifo_hal_set_vtotal_ext(true, u4Votal, mode);
	}
}
#endif

