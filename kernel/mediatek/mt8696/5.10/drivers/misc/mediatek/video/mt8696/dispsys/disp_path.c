int disp_path_set_res(struct disp_path_resolution *resolution)
{
	bool path_change = false;

	DISP_LOG_I("jancsi set res: %d\n", resolution->res);

	if (disp_path.resolution.res == resolution->res)
		return 0;

	if (disp_path.resolution.is_progressive != resolution->is_progressive) {
		disp_path.resolution.is_progressive =
			resolution->is_progressive;
		path_change = true;
	}

	_save_resolution_info(resolution);

	if (path_change)
		disp_path_set_hw_path(DISP_PATH_DISP_P2I,
			!disp_path.resolution.is_progressive);

	return 0;
}

int disp_path_init(struct disp_path_resolution *resolution)
{
	_save_resolution_info(resolution);
	disp_path.resolution.is_progressive =
		resolution->is_progressive;
	disp_path.main_path_dolby_enable = false;
	disp_path.sub_path_dolby_enable = false;
	disp_path.fhd_gfx_dolby_enable = false;
	disp_path.uhd_gfx_dolby_enable = false;
	fs_index[0] = 0;
	fs_index[1] = 0;
	return 0;
}
