int disp_path_get_active_zone(enum DISP_PATH_HW_ID id,
			      enum HDMI_VIDEO_RESOLUTION res, int *h_start,
			      int *v_odd_start, int *v_even_start)
{
	struct full_screen_param *fs_param = NULL;
	int idx = _get_fs_index(id);

	if (idx >= FULL_SCREEN_IDX) {
		DISP_LOG_N("get active idx=%d error.\n", idx);
		return -1;
	}

	fs_param = _get_fs_param(id, idx, res);
	if (fs_param == NULL || fs_param->res != res) {
		DISP_LOG_N(
			"get active param is null or resolution is wrong.\n");
		return -1;
	}

	*h_start = fs_param->h_start;
	*v_odd_start = fs_param->v_odd_start;
	*v_even_start = fs_param->v_even_start;

	DISP_LOG_HW(
		"id: %d, h_s: 0x%x, v_odd_s: 0x%x, v_even_s: 0x%x, res: %d %d\n",
		id, *h_start, *v_odd_start, *v_even_start, res, idx);

	return 0;
}

int disp_path_get_sof_info(enum DISP_SOF_TYPE start_type,
	enum DISP_SOF_TYPE end_type, int *sof_start, int *sof_end)
{
	int i = 0;
	struct sof_param *fs_point = NULL;
	struct sof_param *fs_table = NULL;
	int idx = 0;

	if (idx >= FULL_SCREEN_IDX) {
		DISP_LOG_N("get delay info idx=%d error.\n", idx);
		return -1;
	}
	fs_table = &sof_table[idx][0];
	for (i = 0; i < (DISP_SOF_NUM/2); i = i+1) {
		if ((fs_table[i].start_type == start_type) &&
			(fs_table[i].end_type == end_type)) {
			fs_point = &fs_table[i];
			break;
		}
	}

	if (fs_point != NULL) {
		*sof_start = fs_point->sof_start;
		*sof_end = fs_point->sof_end;
	}

	FMT_LOG_D(
		"start_type: %d, end_type: %d, sof_s: 0x%x, sof_e: 0x%x\n",
		start_type, end_type, *sof_start, *sof_end);
	return 0;
}


