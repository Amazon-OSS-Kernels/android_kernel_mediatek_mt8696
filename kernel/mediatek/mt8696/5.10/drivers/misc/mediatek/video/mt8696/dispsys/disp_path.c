struct disp_path_context disp_path;

uint32_t fs_index[2];

void set_fs_index(uint32_t layer_id, uint32_t index)
{
	if (fs_index[layer_id] != index) {
		fs_index[layer_id] = index;
		DISP_LOG_N("%s %d %d\n", __func__, layer_id, index);
	}
}
static int _get_fs_index(enum DISP_PATH_HW_ID id)
{
	if (id == DISP_PATH_S_VDO) {
		if (fs_index[1] == 1)
			return 1;
	} else {
		if (fs_index[0] == 1)
			return 1;
	}

	return 0;
}

static struct full_screen_param *_get_fs_param(enum DISP_PATH_HW_ID id, int idx,
					       enum HDMI_VIDEO_RESOLUTION res)
{
	int i = 0;
	struct full_screen_param *fs_table = NULL;
	struct full_screen_param *fs_point = NULL;

	if (id == DISP_PATH_M_VDO)
		fs_table = &(mvdo_table[idx][0]);
	else if (id == DISP_PATH_S_VDO)
		fs_table = &(svdo_table[idx][0]);
	else if (id == DISP_PATH_FHD_OSD)
		fs_table = &(osd1_table[idx][0]);
	else if (id == DISP_PATH_UHD_OSD)
		fs_table = &(osd2_table[idx][0]);
	else if (id == DISP_PATH_M_VDO_OUT)
		fs_table = &(mvdo_out_table[idx][0]);
	else if (id == DISP_PATH_S_VDO_OUT)
		fs_table = &(svdo_out_table[idx][0]);
	else if (id == DISP_PATH_DISP_HDR_VDO_BE)
		fs_table = &(hdr_vdo_be_table[idx][0]);
	else
		return NULL;

	for (i = 0; i < HDMI_VIDEO_RESOLUTION_NUM; i++) {
		if (fs_table[i].res == res) {
			fs_point = &fs_table[i];
			break;
		}
	}

	return fs_point;
}

static void _save_resolution_info(struct disp_path_resolution *resolution)
{
	if (disp_path.resolution.res == resolution->res)
		return;

	memcpy((void *)&disp_path.resolution, (void *)resolution,
	       sizeof(struct disp_path_resolution));
}

int disp_path_set_hw_path(enum DISP_PATH_HW_ID id, bool enable)
{
	/* setting disp path */
	FMT_LOG_D("%s, id:%d\n", __func__, id);

	switch (id) {
	case DISP_PATH_M_VDO:
	case DISP_PATH_DISP_R2R:
	case DISP_PATH_DISP_DGI:
		disp_sys_hal_mvdo_out_select(id, enable);
		if (enable)
			disp_sys_hal_m_film_grain_enable(false);
		if (enable && disp_path.main_path_dolby_enable)
			disp_sys_hal_m_hdr_vdo_fe_enable(true);
		break;
	case DISP_PATH_M_FILM_GRAIN:
		disp_sys_hal_m_film_grain_enable(enable);
		break;
	case DISP_PATH_M_HDR_VDO_FE:
		disp_sys_hal_m_hdr_vdo_fe_enable(enable);
		disp_path.main_path_dolby_enable = enable;
		break;
	case DISP_PATH_S_VDO:
		disp_sys_hal_svdo_out_select(enable);
		if (enable)
			disp_sys_hal_s_film_grain_enable(false);
		if (enable && disp_path.sub_path_dolby_enable)
			disp_sys_hal_s_hdr_vdo_fe_enable(true);
		break;
	case DISP_PATH_S_FILM_GRAIN:
		disp_sys_hal_s_film_grain_enable(enable);
		break;
	case DISP_PATH_S_HDR_VDO_FE:
		disp_sys_hal_s_hdr_vdo_fe_enable(enable);
		disp_path.sub_path_dolby_enable = enable;
		break;
	case DISP_PATH_FHD_OSD:
		if (enable)
			vdout_sys_hal_fhd_hdr_gfx_fe_enable(true);
		break;
	case DISP_PATH_FHD_HDR_GFX_FE:
		vdout_sys_hal_fhd_hdr_gfx_fe_enable(enable);
		disp_path.fhd_gfx_dolby_enable = enable;
		break;
	case DISP_PATH_UHD_OSD:
		if (enable)
			vdout_sys_hal_uhd_hdr_gfx_fe_enable(true);
		break;
	case DISP_PATH_UHD_HDR_GFX_FE:
		vdout_sys_hal_uhd_hdr_gfx_fe_enable(enable);
		disp_path.uhd_gfx_dolby_enable = enable;
		break;
	case DISP_PATH_DISP_HDR_VDO_BE:
		vdout_sys_hal_hdr_vdo_be_enable(enable);
		break;
	case DISP_PATH_DISP_P2I:
		if (enable) {
			vdout_sys_rgb2hdmi_input_mux_src_select(enable);
			vdout_sys_rgb2hdmi_input_timing_select(enable);
			vdout_sys_p2i_input_mux_src_select();
			vdout_sys_vm_input_mux_src_select(enable);
			vdout_sys_vm_output_mux_src_select(enable);
		} else {
			vdout_sys_rgb2hdmi_input_mux_src_select(enable);
			vdout_sys_rgb2hdmi_input_timing_select(enable);
			vdout_sys_vm_input_mux_src_select(enable);
			vdout_sys_vm_output_mux_src_select(enable);
		}
		break;
	default:
		DISP_LOG_N("%s, not processed hw id:%d\n", __func__, id);
		break;
	}

	/*default path is which four layers are all through disp_mix */
	vdout_sys_hal_4_layers_hdr_gfx2_mix_sout_select();

	if (!disp_path.resolution.is_progressive) {
		vdout_sys_rgb2hdmi_input_mux_src_select(true);
		vdout_sys_p2i_input_mux_src_select();
		vdout_sys_vm_input_mux_src_select(true);
		vdout_sys_vm_output_mux_src_select(true);
		vdout_sys_rgb2hdmi_input_timing_select(true);
	} else {
		vdout_sys_vm_input_mux_src_select(false);
		vdout_sys_vm_output_mux_src_select(false);
		vdout_sys_rgb2hdmi_input_mux_src_select(false);
		vdout_sys_rgb2hdmi_input_timing_select(false);
	}

#ifdef DISP_PATH_SHADOW_ENABLE
	/* mux shadow update*/
	fmt_hal_shadow_update();
#endif

	return 0;
}

